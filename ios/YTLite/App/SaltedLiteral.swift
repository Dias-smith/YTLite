import Foundation

/// Reveals XOR-salted literals so sensitive tokens never sit plainly in the binary.
enum SaltedLiteral {
    private static let salt: UInt8 = 0xA7

    static func reveal(_ bytes: [UInt8]) -> String {
        String(decoding: bytes.map { $0 ^ salt }, as: UTF8.self)
    }

    static var playbackMediaFolder: String {
        reveal([
            0xD7, 0xCB, 0xC6, 0xDE, 0xC5, 0xC6, 0xC4, 0xCC, 0xF8, 0xCA, 0xC2, 0xC3, 0xCE, 0xC6,
        ])
    }

    static var indexFileName: String {
        reveal([0xCE, 0xC9, 0xC3, 0xC2, 0xDF, 0x89, 0xCD, 0xD4, 0xC8, 0xC9])
    }

    static var probeHit: String {
        reveal([
            0xD7, 0xCB, 0xC6, 0xDE, 0x89, 0xD4, 0xD3, 0xC8, 0xD5, 0xC2, 0x89, 0xCF, 0xCE, 0xD3,
        ])
    }

    static var probeStale: String {
        reveal([
            0xD7, 0xCB, 0xC6, 0xDE, 0x89, 0xD4, 0xD3, 0xC8, 0xD5, 0xC2, 0x89, 0xD4, 0xD3, 0xC6, 0xCB,
            0xC2,
        ])
    }

    static var probeSchedule: String {
        reveal([
            0xD7, 0xCB, 0xC6, 0xDE, 0x89, 0xD4, 0xD3, 0xC8, 0xD5, 0xC2, 0x89, 0xD4, 0xC4, 0xCF, 0xC2,
            0xC3, 0xD2, 0xCB, 0xC2,
        ])
    }

    static var probeSaved: String {
        reveal([
            0xD7, 0xCB, 0xC6, 0xDE, 0x89, 0xD4, 0xD3, 0xC8, 0xD5, 0xC2, 0x89, 0xD4, 0xC6, 0xD1, 0xC2,
            0xC3,
        ])
    }

    static var probeCancelled: String {
        reveal([
            0xD7, 0xCB, 0xC6, 0xDE, 0x89, 0xD4, 0xD3, 0xC8, 0xD5, 0xC2, 0x89, 0xC4, 0xC6, 0xC9, 0xC4,
            0xC2, 0xCB, 0xCB, 0xC2, 0xC3,
        ])
    }

    static var probeFail: String {
        reveal([
            0xD7, 0xCB, 0xC6, 0xDE, 0x89, 0xD4, 0xD3, 0xC8, 0xD5, 0xC2, 0x89, 0xC1, 0xC6, 0xCE, 0xCB,
        ])
    }

    static var probeEvict: String {
        reveal([
            0xD7, 0xCB, 0xC6, 0xDE, 0x89, 0xD4, 0xD3, 0xC8, 0xD5, 0xC2, 0x89, 0xC2, 0xD1, 0xCE, 0xC4,
            0xD3,
        ])
    }

    static var probeLocalSource: String {
        reveal([0xCB, 0xC8, 0xC4, 0xC6, 0xCB])
    }
}
